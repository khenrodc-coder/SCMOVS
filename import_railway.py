# Count SQL object declarations, including DEFINER clauses.
triggers = sum(
    bool(re.match(
        r"CREATE\s+(?:OR\s+REPLACE\s+)?(?:DEFINER\s*=\s*\S+\s+)?TRIGGER\b",
        s, re.I
    ))
    for s in normalized
)
tables = sum(
    bool(re.match(r"CREATE\s+TABLE\b", s, re.I))
    for s in normalized
)
inserts = sum(
    bool(re.match(r"INSERT\s+INTO\b", s, re.I))
    for s in normalized
)
views = sum(
    bool(re.match(
        r"CREATE\s+(?:OR\s+REPLACE\s+)?(?:ALGORITHM\s*=\s*\S+\s+)?"
        r"(?:DEFINER\s*=\s*\S+\s+)?(?:SQL\s+SECURITY\s+\w+\s+)?VIEW\b",
        s, re.I
    ))
    for s in normalized
)

print("Tables:", tables, "Inserts:", inserts,
      "Triggers:", triggers, "Views:", views)


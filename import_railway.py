# Remove MariaDB client delimiter directives while using their
# values to split statements correctly.


def split_sql(source):
    delimiter = ";"
    statements = []
    buffer = []
    quote = None
    line_comment = False
    block_comment = False
    i = 0

    while i < len(source):
        line_start = i == 0 or source[i - 1] == "\n"

        # DELIMITER is a MySQL/MariaDB client directive, not SQL.
        # Recognize it even when comments are waiting in the buffer.
        if line_start and quote is None and not line_comment and not block_comment:
            match = re.match(
                r"[ \t]*DELIMITER[ \t]+(\S+)[ \t]*(?:\r?\n|$)",
                source[i:],
                re.IGNORECASE
            )
            if match:
                delimiter = match.group(1)
                i += match.end()
                continue

        ch = source[i]
        nxt = source[i + 1] if i + 1 < len(source) else ""

        if line_comment:
            buffer.append(ch)
            if ch == "\n":
                line_comment = False

        elif block_comment:
            buffer.append(ch)
            if ch == "*" and nxt == "/":
                buffer.append(nxt)
                i += 1
                block_comment = False

        elif quote:
            buffer.append(ch)
            if ch == "\\" and quote in ("'", '"') and nxt:
                buffer.append(nxt)
                i += 1
            elif ch == quote:
                if nxt == quote:
                    buffer.append(nxt)
                    i += 1
                else:
                    quote = None

        elif ch in ("'", '"', "`"):
            quote = ch
            buffer.append(ch)

        elif ch == "#":
            line_comment = True
            buffer.append(ch)

        elif ch == "-" and nxt == "-" and (
            i + 2 >= len(source) or source[i + 2].isspace()
        ):
            line_comment = True
            buffer.extend([ch, nxt])
            i += 1

        elif ch == "/" and nxt == "*":
            block_comment = True
            buffer.extend([ch, nxt])
            i += 1

        elif source.startswith(delimiter, i):
            statement = "".join(buffer).strip()
            if statement:
                statements.append(statement)
            buffer = []
            i += len(delimiter) - 1

        else:
            buffer.append(ch)

        i += 1

    remainder = "".join(buffer).strip()
    if remainder:
        statements.append(remainder)

    return statements


statements = split_sql(sql)


# Remove the two view drops generated by the MariaDB export.
cleaned = []
for stmt in statements:
    if re.match(
        r"DROP\s+TABLE\s+IF\s+EXISTS\s+`v_election_(participation|results)`\s*$",
        stmt, re.I
    ):
        continue

    # Use the Railway account rather than the local XAMPP definer.
    stmt = re.sub(
        r"\bDEFINER\s*=\s*`root`@`localhost`\s*",
        "",
        stmt,
        flags=re.I
    )
    cleaned.append(stmt)

print("Backup:", backup)

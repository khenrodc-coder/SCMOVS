"""Sending a new account holder their initial password by email.

The password is generated by the server, stored only as a hash, and emailed once to the address on the account.
The audit log records THAT it was sent, never the password. The new user is forced to change it at first login.
If the email cannot be sent, the account still exists and the caller shows the password once to the admin, so the
user is never locked out.
"""
from flask import current_app, url_for

from app.audit.services import log_action
from app.mail_templates import welcome_email
from app.mailer import MailNotConfigured, MailSendError, mail_is_configured, send_mail


def mask_email(email):
    if not email or "@" not in email:
        return ""
    local, _, domain = email.partition("@")
    return (local[:2] + "***@" + domain) if len(local) > 2 else ("***@" + domain)


def email_initial_password(to_address, full_name, username, password, actor_id, record):
    """Email the initial password. Returns (sent, problem). `problem` is a short reason when sent is False."""
    base_url = current_app.config.get("PUBLIC_BASE_URL", "")
    if not mail_is_configured() or not base_url:
        return False, "Email (SMTP) is not configured on the server."
    subject, text, html = welcome_email(full_name, username, password, base_url + url_for("auth.login"),
                                        current_app.config.get("SYSTEM_NAME", "Student Council Management and Online Voting System"))
    try:
        send_mail(to_address, subject, text, html)
    except (MailNotConfigured, MailSendError):
        log_action(actor_id, "initial_password_email_failed", "users",
                   f"Initial password email to {mask_email(to_address)} could not be sent", affected_record=record)
        return False, "The email server could not send the message."
    log_action(actor_id, "initial_password_emailed", "users",
               f"Initial password emailed to {mask_email(to_address)}", affected_record=record)
    return True, None
